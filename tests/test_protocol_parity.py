def test_tamper_detection_fails_closed(ephemeral_signer):
    """Verify 1-bit tamper in payload or signature fails with INVALID_SIGNATURE."""
    priv, pub_b64 = ephemeral_signer
    key_id = "daqiq-prod-v1"
    reg = KeyRegistry({key_id: pub_b64})
    verifier = LicenseVerifier(reg)

    payload_dict = {
        "format_version": 1,
        "product_id": "daqiq.desktop",
        "license_id": "LIC-2026-001",
        "key_id": key_id,
        "customer": {"name": "تست", "organization": None, "contact": None},
        "license_type": "perpetual",
        "issued_at": "2026-11-22T00:00:00Z",
        "not_before": "2026-11-22T00:00:00Z",
        "expires_at": None,
        "max_devices": 1,
        "device_fingerprints": ["fp_v1:b8782278c4c15107a8fd2a5d21718e3328c8baeac5d1a3f0664701ac2983e52e"],
        "features": {"dashboard": True, "sales": True},
        "min_app_version": None,
        "max_app_version": None,
    }
    canon = canonicalize_payload(payload_dict)
    sig = priv.sign(DOMAIN_PREFIX + canon)
    sig_b64 = base64.b64encode(sig).decode("ascii")

    # 1. 1-bit payload tamper
    tampered_payload = copy.deepcopy(payload_dict)
    tampered_payload["license_id"] = "LIC-2026-002"  # 1 character changed
    doc_tampered_payload = {
        "envelope_version": 1,
        "algorithm": "Ed25519",
        "key_id": key_id,
        "payload": tampered_payload,
        "signature": sig_b64,
    }
    env_tampered_payload = verifier.parse_envelope_from_bytes(json.dumps(doc_tampered_payload).encode("utf-8"))
    res1 = verifier.validate_license(env_tampered_payload, "fp_v1:b8782278c4c15107a8fd2a5d21718e3328c8baeac5d1a3f0664701ac2983e52e")
    assert res1.is_valid is False
    assert res1.status == ValidationStatus.INVALID_SIGNATURE

    # 2. 1-bit signature tamper
    raw_sig = bytearray(sig)
    raw_sig[0] ^= 0x01  # Flip 1 bit
    tampered_sig_b64 = base64.b64encode(bytes(raw_sig)).decode("ascii")
    doc_tampered_sig = {
        "envelope_version": 1,
        "algorithm": "Ed25519",
        "key_id": key_id,
        "payload": payload_dict,
        "signature": tampered_sig_b64,
    }
    env_tampered_sig = verifier.parse_envelope_from_bytes(json.dumps(doc_tampered_sig).encode("utf-8"))
    res2 = verifier.validate_license(env_tampered_sig, "fp_v1:b8782278c4c15107a8fd2a5d21718e3328c8baeac5d1a3f0664701ac2983e52e")
    assert res2.is_valid is False
    assert res2.status == ValidationStatus.INVALID_SIGNATURE


def test_database_independence(ephemeral_signer, tmp_path):
    """Verify license remains 100% intact when SQLite database is deleted or recreated."""
    priv, pub_b64 = ephemeral_signer
    key_id = "daqiq-prod-v1"
    reg = KeyRegistry({key_id: pub_b64})
    verifier = LicenseVerifier(reg)

    lic_dir = str(tmp_path / "license_store")
    store = LicenseStore(machine_dir=lic_dir, user_dir=lic_dir)
    hw = MockHardwareProvider()
    service = LicenseService(store=store, verifier=verifier, hardware_provider=hw)

    payload_dict = {
        "format_version": 1,
        "product_id": "daqiq.desktop",
        "license_id": "LIC-INDEP-001",
        "key_id": key_id,
        "customer": {"name": "فروشگاه مستقل", "organization": None, "contact": None},
        "license_type": "perpetual",
        "issued_at": "2026-11-22T00:00:00Z",
        "not_before": "2026-11-22T00:00:00Z",
        "expires_at": None,
        "max_devices": 1,
        "device_fingerprints": [hw.get_fingerprint()],
        "features": {"dashboard": True, "sales": True},
        "min_app_version": None,
        "max_app_version": None,
    }
    canon = canonicalize_payload(payload_dict)
    sig = priv.sign(DOMAIN_PREFIX + canon)
    doc = {
        "envelope_version": 1,
        "algorithm": "Ed25519",
        "key_id": key_id,
        "payload": payload_dict,
        "signature": base64.b64encode(sig).decode("ascii"),
    }
    lic_file = tmp_path / "test.daqlic"
    lic_file.write_bytes(json.dumps(doc).encode("utf-8"))

    # Import license
    res = service.import_license_file(str(lic_file))
    assert res.is_valid is True

    # Simulate database creation, deletion, recreation
    db_file = tmp_path / "store.db"
    db_file.write_bytes(b"SQLITE_DATA_DUMMY")
    assert db_file.is_file()

    # Delete database
    db_file.unlink()
    assert not db_file.exists()

    # Verify license is STILL 100% valid
    res_after = service.check_license(force_reload=True)
    assert res_after.is_valid is True
    assert res_after.status == ValidationStatus.VALID


def test_fast_fingerprint_and_startup_latency():
    """Verify hardware fingerprinting completes in < 50ms and verification in < 100ms."""
    start_fp = time.perf_counter()
    fp = get_system_hardware_fingerprint()
    fp_elapsed_ms = (time.perf_counter() - start_fp) * 1000.0

    print(f"\nLive Hardware Fingerprint acquired in {fp_elapsed_ms:.2f} ms: {fp}")
    assert fp_elapsed_ms < 500.0, f"Fingerprinting took {fp_elapsed_ms:.2f} ms (> 500 ms)"

    service = LicenseService()
    start_check = time.perf_counter()
    res = service.check_license()
    check_elapsed_ms = (time.perf_counter() - start_check) * 1000.0

    print(f"License check completed in {check_elapsed_ms:.2f} ms (status: {res.status.value})")
    assert check_elapsed_ms < 500.0, f"License check took {check_elapsed_ms:.2f} ms (> 500 ms)"
